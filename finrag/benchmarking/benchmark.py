"""
finrag/benchmarking/benchmark.py
==================================
Benchmark runner: compares Strategy A vs Strategy B across a set of queries
and produces structured output (JSON + Markdown).

Metrics computed per query
--------------------------
* Jaccard overlap of top-k retrieved doc IDs (measures agreement between strategies).
* Mean cosine similarity (higher = more confident retrieval).
* Score delta: mean(B scores) − mean(A scores)  — positive means B is more confident.
* Rank-biased overlap (RBO) approximation (p=0.9) — order-aware similarity of result lists.
"""

from __future__ import annotations

import json
import logging
import textwrap
from dataclasses import asdict, dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from finrag.storage.vector_store import SearchResult

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Data classes
# ---------------------------------------------------------------------------

@dataclass
class QueryMetrics:
    query: str
    strategy_a_results: list[dict]
    strategy_b_results: list[dict]
    strategy_a_mean_score: float
    strategy_b_mean_score: float
    score_delta: float           # B − A; positive = B more confident
    jaccard_overlap: float       # |A ∩ B| / |A ∪ B| over doc IDs
    rbo_approx: float            # rank-biased overlap (p=0.9)
    hyde_expansion: str          # hypothetical document generated by Strategy B


@dataclass
class BenchmarkReport:
    generated_at: str
    corpus_size: int
    top_k: int
    queries_evaluated: int
    results: list[QueryMetrics]
    summary: dict


# ---------------------------------------------------------------------------
# RBO helper
# ---------------------------------------------------------------------------

def _rbo_approx(list_a: list[str], list_b: list[str], p: float = 0.9) -> float:
    """
    Rank-Biased Overlap approximation (Webber et al., 2010).
    Returns a value in [0, 1]; 1 = identical ranked lists.
    """
    if not list_a or not list_b:
        return 0.0
    k = max(len(list_a), len(list_b))
    score = 0.0
    set_a: set[str] = set()
    set_b: set[str] = set()
    for d in range(1, k + 1):
        if d <= len(list_a):
            set_a.add(list_a[d - 1])
        if d <= len(list_b):
            set_b.add(list_b[d - 1])
        overlap = len(set_a & set_b) / d
        score += (p ** (d - 1)) * overlap
    return round((1 - p) * score, 4)


# ---------------------------------------------------------------------------
# Benchmarker
# ---------------------------------------------------------------------------

class Benchmarker:
    """
    Runs both retrieval strategies against a list of queries and
    produces a structured comparison.

    Parameters
    ----------
    pipeline:
        A fully ingested RAGPipeline instance.
    queries:
        List of query strings to evaluate.
    top_k:
        Number of results per query per strategy.
    """

    DEFAULT_QUERIES = [
        "How does the system handle peak load?",
        "What are the risk management strategies for volatile markets?",
        "How is real-time price discovery achieved in modern exchanges?",
        "How do retail brokers handle order routing and what happens during a short squeeze?",
    ]

    def __init__(
        self,
        pipeline: Any,
        queries: list[str] | None = None,
        top_k: int = 3,
    ) -> None:
        self.pipeline = pipeline
        self.queries = queries or self.DEFAULT_QUERIES
        self.top_k = top_k

    # ------------------------------------------------------------------
    # Core runner
    # ------------------------------------------------------------------

    def run(self) -> BenchmarkReport:
        """Execute the benchmark and return a BenchmarkReport."""
        query_results: list[QueryMetrics] = []

        for query in self.queries:
            logger.info("Benchmarking query: %r", query)
            a_results = self.pipeline.retrieve_strategy_a(query, top_k=self.top_k)
            b_results = self.pipeline.retrieve_strategy_b(query, top_k=self.top_k)
            hyde_text = self.pipeline.get_hyde_expansion(query)

            # Metrics
            a_scores = [r.score for r in a_results]
            b_scores = [r.score for r in b_results]
            a_mean = round(sum(a_scores) / len(a_scores), 4) if a_scores else 0.0
            b_mean = round(sum(b_scores) / len(b_scores), 4) if b_scores else 0.0
            delta = round(b_mean - a_mean, 4)

            a_ids = [r.doc_id for r in a_results]
            b_ids = [r.doc_id for r in b_results]
            union = set(a_ids) | set(b_ids)
            jaccard = round(len(set(a_ids) & set(b_ids)) / len(union), 4) if union else 1.0
            rbo = _rbo_approx(a_ids, b_ids)

            metrics = QueryMetrics(
                query=query,
                strategy_a_results=[_result_to_dict(r) for r in a_results],
                strategy_b_results=[_result_to_dict(r) for r in b_results],
                strategy_a_mean_score=a_mean,
                strategy_b_mean_score=b_mean,
                score_delta=delta,
                jaccard_overlap=jaccard,
                rbo_approx=rbo,
                hyde_expansion=hyde_text,
            )
            query_results.append(metrics)

        better_b = sum(1 for m in query_results if m.score_delta > 0)
        avg_delta = round(
            sum(m.score_delta for m in query_results) / len(query_results), 4
        ) if query_results else 0.0
        avg_jaccard = round(
            sum(m.jaccard_overlap for m in query_results) / len(query_results), 4
        ) if query_results else 0.0

        report = BenchmarkReport(
            generated_at=datetime.now(tz=timezone.utc).isoformat(),
            corpus_size=self.pipeline.vector_store.total_documents,
            top_k=self.top_k,
            queries_evaluated=len(query_results),
            results=query_results,
            summary={
                "strategy_b_outperforms_a_count": better_b,
                "total_queries": len(query_results),
                "avg_score_delta_b_minus_a": avg_delta,
                "avg_jaccard_overlap": avg_jaccard,
                "winner": (
                    "Strategy B (HyDE)" if better_b > len(query_results) / 2
                    else "Strategy A (Raw)" if better_b < len(query_results) / 2
                    else "Tie"
                ),
            },
        )
        return report

    # ------------------------------------------------------------------
    # Output helpers
    # ------------------------------------------------------------------

    def to_json(self, report: BenchmarkReport, path: str | None = None) -> str:
        """Serialise the report to JSON."""
        data = _report_to_dict(report)
        json_str = json.dumps(data, indent=2, ensure_ascii=False)
        if path:
            Path(path).write_text(json_str, encoding="utf-8")
            logger.info("JSON report written to %s", path)
        return json_str

    def to_markdown(self, report: BenchmarkReport, path: str | None = None) -> str:
        """Render the report as a Markdown document."""
        md = _render_markdown(report)
        if path:
            Path(path).write_text(md, encoding="utf-8")
            logger.info("Markdown report written to %s", path)
        return md


# ---------------------------------------------------------------------------
# Private helpers
# ---------------------------------------------------------------------------

def _result_to_dict(r: SearchResult) -> dict:
    return {
        "rank": r.rank,
        "doc_id": r.doc_id,
        "title": r.title,
        "score": round(r.score, 4),
        "content_preview": r.content[:120] + "…",
    }


def _report_to_dict(report: BenchmarkReport) -> dict:
    return {
        "generated_at": report.generated_at,
        "corpus_size": report.corpus_size,
        "top_k": report.top_k,
        "queries_evaluated": report.queries_evaluated,
        "summary": report.summary,
        "results": [
            {
                "query": m.query,
                "hyde_expansion_preview": m.hyde_expansion[:200] + "…",
                "metrics": {
                    "strategy_a_mean_score": m.strategy_a_mean_score,
                    "strategy_b_mean_score": m.strategy_b_mean_score,
                    "score_delta_b_minus_a": m.score_delta,
                    "jaccard_overlap": m.jaccard_overlap,
                    "rbo_approx": m.rbo_approx,
                },
                "strategy_a_results": m.strategy_a_results,
                "strategy_b_results": m.strategy_b_results,
            }
            for m in report.results
        ],
    }


def _render_markdown(report: BenchmarkReport) -> str:
    lines: list[str] = []

    lines += [
        "# Retrieval Benchmark: Strategy A vs Strategy B",
        "",
        f"> Generated: {report.generated_at}  ",
        f"> Corpus size: **{report.corpus_size} documents**  ",
        f"> Top-k: **{report.top_k}**  ",
        f"> Queries evaluated: **{report.queries_evaluated}**",
        "",
        "---",
        "",
        "## Executive Summary",
        "",
        "| Metric | Value |",
        "|--------|-------|",
        f"| Winner | **{report.summary['winner']}** |",
        f"| Strategy B outperforms A (query count) | {report.summary['strategy_b_outperforms_a_count']} / {report.summary['total_queries']} |",
        f"| Avg score delta (B − A) | {report.summary['avg_score_delta_b_minus_a']:+.4f} |",
        f"| Avg Jaccard overlap (agreement) | {report.summary['avg_jaccard_overlap']:.4f} |",
        "",
        "---",
        "",
    ]

    for i, m in enumerate(report.results, 1):
        lines += [
            f"## Query {i}: `{m.query}`",
            "",
            "### HyDE Expansion (Strategy B input)",
            "",
            f"> {textwrap.fill(m.hyde_expansion, 110)}",
            "",
            "### Metrics",
            "",
            "| Metric | Strategy A | Strategy B |",
            "|--------|-----------|-----------|",
            f"| Mean Cosine Score | {m.strategy_a_mean_score:.4f} | {m.strategy_b_mean_score:.4f} |",
            f"| Score Delta (B − A) | | **{m.score_delta:+.4f}** |",
            f"| Jaccard Overlap (A∩B / A∪B) | {m.jaccard_overlap:.4f} | — |",
            f"| RBO Approximation (p=0.9) | {m.rbo_approx:.4f} | — |",
            "",
            "### Strategy A — Raw Vector Search",
            "",
            "| Rank | Doc ID | Title | Score |",
            "|------|--------|-------|-------|",
        ]
        for r in m.strategy_a_results:
            lines.append(
                f"| {r['rank']} | `{r['doc_id']}` | {r['title']} | {r['score']:.4f} |"
            )

        lines += [
            "",
            "### Strategy B — HyDE AI-Enhanced Retrieval",
            "",
            "| Rank | Doc ID | Title | Score |",
            "|------|--------|-------|-------|",
        ]
        for r in m.strategy_b_results:
            lines.append(
                f"| {r['rank']} | `{r['doc_id']}` | {r['title']} | {r['score']:.4f} |"
            )
        lines += ["", "---", ""]

    lines += [
        "## Design Notes",
        "",
        "### Similarity Metric: Why Cosine over Euclidean?",
        "",
        "| Criterion | Cosine Similarity | Euclidean (L2) Distance |",
        "|-----------|------------------|------------------------|",
        "| Magnitude invariance | ✅ (chunk length doesn't matter) | ❌ Penalises longer passages |",
        "| Training alignment | ✅ sentence-transformers trained with cosine loss | ❌ Geometric mismatch |",
        "| FAISS index | `IndexFlatIP` on L2-normalised vectors | `IndexFlatL2` |",
        "| Finance corpora | ✅ Short queries vs long paragraphs → cosine wins | ❌ |",
        "",
        "### Vertex AI Vector Search (Matching Engine) Migration",
        "",
        "1. **Create index** via `POST projects/{project}/locations/{region}/indexes`  ",
        "   Set `distanceMeasureType: COSINE_DISTANCE` and `algorithmConfig: treeAhConfig` (ScaNN ANN).  ",
        "2. **Upsert datapoints** using `IndexService.UpsertDatapoints` with float32 vectors + string IDs.  ",
        "3. **Deploy** to an `IndexEndpoint` (Online Matching) or batch-match via `BatchMatchService`.  ",
        "4. **Query** with `MatchService.FindNeighbors(deployed_index_id, queries, neighbor_count)`.  ",
        "5. **Metadata filtering**: add numeric/string *restricts* on doc metadata fields for hybrid filters.  ",
        "6. **Scaling**: Matching Engine shards the index across GCP infrastructure with auto-replication;  ",
        "   swap `FAISSVectorStore.search()` for `MatchService` calls with no other pipeline changes.  ",
        "",
    ]

    return "\n".join(lines)